function initial() {
  try {
    const saved = localStorage.getItem('smile-lang');
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* storage not available */ }
  return 'de'; // the practice works in German; English is one tap away
}

let lang = initial();
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'de';
  document.documentElement.lang = lang;
  try {
    localStorage.setItem('smile-lang', lang);
  } catch { /* storage not available */ }
}

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// Picks the right language from a { de, en } object.
export const tr = (o) => (typeof o === 'string' ? o : o?.[lang] ?? o?.de ?? '');

export const dateLocale = () => (lang === 'en' ? 'en-GB' : 'de-DE');
